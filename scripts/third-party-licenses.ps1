# Collect the license texts of everything shipped inside Shellmosaic — the Rust crates
# compiled into the app and the npm packages bundled into its UI — into
# THIRD-PARTY-LICENSES.txt. Identical texts are written once, under every package that uses them.
#
#   pwsh scripts/third-party-licenses.ps1
$ErrorActionPreference = "Stop"
$root = Split-Path $PSScriptRoot -Parent
$packages = [System.Collections.Generic.List[object]]::new()

function Add-Package($name, $version, $license, $dir) {
  $packages.Add([pscustomobject]@{ Name = $name; Version = $version; License = $license; Dir = $dir })
}

# Rust: normal (shipped) dependencies of the app, for Windows
$meta = cargo metadata --format-version 1 --locked --manifest-path "$root\src-tauri\Cargo.toml" --filter-platform x86_64-pc-windows-gnu | ConvertFrom-Json
$nodes = @{}; foreach ($n in $meta.resolve.nodes) { $nodes[$n.id] = $n }
$byId = @{}; foreach ($p in $meta.packages) { $byId[$p.id] = $p }
$seen = @{}
$queue = [System.Collections.Generic.Queue[string]]::new()
$queue.Enqueue($meta.resolve.root)
while ($queue.Count) {
  $id = $queue.Dequeue()
  if ($seen[$id]) { continue }
  $seen[$id] = $true
  foreach ($d in $nodes[$id].deps) {
    if ($d.dep_kinds | Where-Object { $null -eq $_.kind }) { $queue.Enqueue($d.pkg) }
  }
}
foreach ($id in $seen.Keys) {
  if ($id -eq $meta.resolve.root) { continue }
  $p = $byId[$id]
  Add-Package $p.name $p.version $p.license (Split-Path $p.manifest_path)
}

# npm: production dependencies (what Vite bundles into the UI)
$tree = pnpm list --prod --depth Infinity --json --dir $root | ConvertFrom-Json
$npmSeen = @{}
function Walk($deps) {
  if (-not $deps) { return }
  foreach ($prop in $deps.PSObject.Properties) {
    $d = $prop.Value
    $key = "$($prop.Name)@$($d.version)"
    if ($npmSeen[$key]) { continue }
    $npmSeen[$key] = $true
    $pj = Join-Path $d.path "package.json"
    $license = if (Test-Path $pj) { (Get-Content $pj -Raw | ConvertFrom-Json).license } else { "" }
    Add-Package $prop.Name $d.version $license $d.path
    Walk $d.dependencies
  }
}
foreach ($t in @($tree)) { Walk $t.dependencies }

# group packages by identical license text
$groups = [ordered]@{}
$noText = [System.Collections.Generic.List[object]]::new()
foreach ($p in ($packages | Sort-Object Name, Version)) {
  $files = Get-ChildItem $p.Dir -File -ErrorAction SilentlyContinue |
    Where-Object { $_.Name -match '^(LICEN[CS]E|COPYING|NOTICE|UNLICENSE)' } | Sort-Object Name
  if (-not $files) { $noText.Add($p); continue }
  $text = ($files | ForEach-Object { (Get-Content $_.FullName -Raw).Trim() }) -join "`n`n"
  $text = $text -replace "`r`n", "`n"
  # texts that differ only in line wrapping or indentation count as the same
  $key = ($text -replace '\s+', ' ').Trim()
  if (-not $groups.Contains($key)) { $groups[$key] = [pscustomobject]@{ Text = $text; Names = [System.Collections.Generic.List[string]]::new() } }
  $groups[$key].Names.Add("$($p.Name) $($p.Version) ($($p.License))")
}

$rule = "=" * 80
$out = [System.Text.StringBuilder]::new()
[void]$out.AppendLine("Third-party software in Shellmosaic")
[void]$out.AppendLine("")
[void]$out.AppendLine("Shellmosaic is MIT-licensed (see LICENSE). It includes the open-source packages below,")
[void]$out.AppendLine("each under its own license. Generated by scripts/third-party-licenses.ps1.")
foreach ($g in $groups.Values) {
  [void]$out.AppendLine("")
  [void]$out.AppendLine($rule)
  foreach ($name in $g.Names) { [void]$out.AppendLine($name) }
  [void]$out.AppendLine("-" * 80)
  [void]$out.AppendLine($g.Text)
}
if ($noText.Count) {
  [void]$out.AppendLine("")
  [void]$out.AppendLine($rule)
  [void]$out.AppendLine("Packages that ship no license file. They are used under the license named by their SPDX")
  [void]$out.AppendLine("identifier; the standard texts of the Apache-2.0 and MIT licenses appear above.")
  foreach ($p in $noText) { [void]$out.AppendLine("$($p.Name) $($p.Version): $($p.License)") }
}
[IO.File]::WriteAllText("$root\THIRD-PARTY-LICENSES.txt", ($out.ToString() -replace "`r`n", "`n"))
Write-Host "$($packages.Count) packages, $($groups.Count) distinct license texts, $($noText.Count) without a license file"
